-- 1. Profiles Table & Trigger
create table if not exists public.profiles (
  id uuid not null primary key references auth.users(id) on delete cascade,
  user_id text,
  name text,
  department text,
  designation text,
  role text default 'user',
  passcode text,
  score integer not null default 0,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

alter table public.profiles enable row level security;

drop policy if exists "Public profiles are viewable by everyone." on public.profiles;
drop policy if exists "Users can insert their own profile." on public.profiles;
drop policy if exists "Users can update their own profile." on public.profiles;

create policy "Public profiles are viewable by everyone." on public.profiles
  for select using (true);

create policy "Users can insert their own profile." on public.profiles
  for insert with check (auth.uid() = id);

create policy "Users can update their own profile." on public.profiles
  for update using (auth.uid() = id);

-- Trigger to automatically create or update profile when a user signs up
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, user_id, name, department, designation, role, passcode)
  values (
    new.id,
    new.raw_user_meta_data->>'userId',
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'department',
    new.raw_user_meta_data->>'designation',
    coalesce(new.raw_user_meta_data->>'role', 'user'),
    new.raw_user_meta_data->>'passcode'
  )
  on conflict (id) do update set
    user_id = coalesce(excluded.user_id, public.profiles.user_id),
    name = coalesce(excluded.name, public.profiles.name),
    department = coalesce(excluded.department, public.profiles.department),
    designation = coalesce(excluded.designation, public.profiles.designation),
    role = coalesce(excluded.role, public.profiles.role),
    passcode = coalesce(excluded.passcode, public.profiles.passcode),
    updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();


