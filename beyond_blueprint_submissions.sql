create table if not exists public.beyond_blueprint_submissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  problem text not null,
  way_of_outflow text not null,
  created_at timestamp with time zone not null default now(),
  constraint beyond_blueprint_submissions_user_id_key unique (user_id)
);

alter table public.beyond_blueprint_submissions enable row level security;

drop policy if exists "Public blueprint submissions viewable by everyone."
  on public.beyond_blueprint_submissions;
drop policy if exists "Users can insert own blueprint submissions."
  on public.beyond_blueprint_submissions;

create policy "Public blueprint submissions viewable by everyone."
  on public.beyond_blueprint_submissions
  for select
  using (true);

create policy "Users can insert own blueprint submissions."
  on public.beyond_blueprint_submissions
  for insert
  with check (auth.uid() = user_id);

-- The task is completion-only and awards zero points. This function update is
-- required because the original function rejected task9 as an unknown task.
create or replace function public.handle_task_completion(
  task_id_in text,
  user_id_in uuid,
  completed_steps_in int,
  score_earned_in int
)
returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  max_points int;
  max_steps int;
begin
  if auth.uid() is null or auth.uid() <> user_id_in then
    raise exception 'Please sign in to save your own score' using errcode = '42501';
  end if;

  max_points := case task_id_in
    when 'task1' then 7
    when 'task3' then 0
    when 'task4' then 0
    when 'task5' then 3
    when 'task7' then 0
    when 'task8' then 0
    when 'task9' then 0
    else null
  end;
  max_steps := case task_id_in when 'task1' then 7 else 1 end;

  if max_points is null
     or score_earned_in is null
     or completed_steps_in is null
     or score_earned_in < 0
     or score_earned_in > max_points
     or completed_steps_in < 0
     or completed_steps_in > max_steps
     or (completed_steps_in = 0 and score_earned_in <> 0) then
    raise exception 'Invalid task result' using errcode = '22023';
  end if;

  perform 1 from public.profiles where id = user_id_in for update;
  if not found then
    raise exception 'User profile does not exist';
  end if;

  insert into public.user_tasks (user_id, task_id, completed_steps, score, updated_at)
    values (user_id_in, task_id_in, completed_steps_in, score_earned_in, now())
    on conflict (user_id, task_id) do update set
      completed_steps = greatest(user_tasks.completed_steps, excluded.completed_steps),
      score = greatest(user_tasks.score, excluded.score),
      updated_at = case
        when excluded.completed_steps > user_tasks.completed_steps
          or excluded.score > user_tasks.score
        then now()
        else user_tasks.updated_at
      end;

  return public.refresh_user_score(user_id_in);
end;
$$;

revoke all on function public.handle_task_completion(text, uuid, int, int) from public, anon;
grant execute on function public.handle_task_completion(text, uuid, int, int) to authenticated;
